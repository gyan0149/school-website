function lastUser(messages: ChatTurn[]): string {
  return [...messages].reverse().find((m) => m.role === "user")?.content ?? "";
}

// Answers parents' questions from the school's own data; works without any AI service.
export function schoolBotAnswer(question: string, s: School): string {
  const q = question.toLowerCase();
  const has = (...words: string[]) => words.some((w) => q.includes(w));
  const phone = displayPhone(s.hmPhone);
  if (has("admission", "एडमिशन", "दाखिला", "नामांकन", "प्रवेश"))
    return `**${s.name}** में कक्षा ${s.classFrom} से ${s.classTo} तक पढ़ाई होती है।\n\n${admissionGuidelines.map((g) => `- ${g}`).join("\n")}\n\nसही तारीख और सीटों के लिए स्कूल को फ़ोन करें: **${phone}**`;
  if (has("document", "कागज", "कागज़", "दस्तावेज"))
    return `एडमिशन के लिए ज़रूरी कागज़ात:\n\n${requiredDocuments.map((d) => `- ${d}`).join("\n")}`;
  if (has("fee", "फ़ीस", "फीस", "शुल्क", "पैसा"))
    return `सरकारी स्कूल होने के कारण कक्षा 1 से 8 तक पढ़ाई **मुफ़्त** है (RTE कानून)। कोई डोनेशन नहीं लिया जाता। ऊपर की कक्षाओं के शुल्क के लिए स्कूल से पूछें: **${phone}**`;
  if (has("phone", "फ़ोन", "फोन", "contact", "संपर्क", "नंबर", "number", "hm", "प्रधानाध्यापक", "principal"))
    return `प्रधानाध्यापक${s.hmName ? `: **${s.hmName}**` : ""}\n📞 **${phone}**\n\nपता: ${schoolAddress(s)}`;
  if (has("where", "कहाँ", "कहां", "address", "पता", "location", "रास्ता", "map", "नक्शा"))
    return `स्कूल का पता: **${schoolAddress(s)}**\n\nनक्शा देखने के लिए "Contact Us" पेज खोलें।`;
  if (has("class", "कक्षा", "क्लास"))
    return `यहाँ **कक्षा ${s.classFrom} से ${s.classTo}** तक पढ़ाई होती है।`;
  if (has("scheme", "योजना", "scholarship", "छात्रवृत्ति", "साइकिल", "पोशाक", "uniform", "mid-day", "भोजन"))
    return `छात्रों के लिए मुख्य योजनाएँ:\n\n${welfareSchemes.map((w) => `- **${w.name}:** ${w.details}`).join("\n")}\n\nपूरी जानकारी के लिए "AI Learning → छात्रवृत्ति खोजें" देखें।`;
  if (has("time", "समय", "timing", "खुलता", "छुट्टी", "holiday"))
    return `स्कूल का समय और छुट्टियों की सूचना "Notices & Circulars" पेज पर मिलेगी। अभी के लिए स्कूल को फ़ोन करें: **${phone}**`;
  return `मैं स्कूल से जुड़े इन सवालों के जवाब दे सकता हूँ: एडमिशन, कागज़ात, फ़ीस, कक्षाएँ, पता, फ़ोन नंबर, योजनाएँ।\n\nदूसरे सवालों के लिए स्कूल को फ़ोन करें: **${phone}**`;
}

